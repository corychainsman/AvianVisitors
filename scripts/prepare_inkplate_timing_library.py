#!/usr/bin/env python3
"""Prepare a private Inkplate library copy with observational partial timing hooks."""
from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import shutil
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DESTINATION = ROOT / "build/timing-libraries/InkplateLibrary"
DRIVER = Path("src/boards/Inkplate13SPECTRA/Inkplate13SPECTRADriver.cpp")
# Reviewed local driver: rotation-aware partial windows and both-chip PTLW+DTM.
# An upstream change requires reviewing the hook positions and updating this pin.
EXPECTED_DRIVER_SHA256 = "50188041c29bdeb9db7e410803dad2b02acf3b7f332243751fb0284f47249641"
DECLARATION = 'extern "C" void avianInkplatePartialTiming(uint8_t phase) __attribute__((weak));\n\n'
STAMP = """#pragma once
// Generated by prepare_inkplate_timing_library.py; never patch the installed library.
#define AVIAN_PARTIAL_TIMING_VERSION 1
"""


def hook(phase: int) -> str:
    return f"    if (avianInkplatePartialTiming) avianInkplatePartialTiming({phase});\n"


def instrument_driver(original: bytes) -> bytes:
    digest = hashlib.sha256(original).hexdigest()
    if digest != EXPECTED_DRIVER_SHA256:
        raise RuntimeError(
            f"Unsupported Inkplate partial driver SHA256 {digest}; expected "
            f"{EXPECTED_DRIVER_SHA256}. Review the driver before updating the timing patch."
        )
    text = original.decode("utf-8")
    start = text.index("void EPDDriver::displayPartial(")
    end = text.index("\n/**", start)
    body = text[start:end]
    replacements = (
        ("{\n    displayStart();", "{\n" + hook(0) + "    displayStart();"),
        ("    setPanelState(true);", hook(1) + "    setPanelState(true);\n" + hook(2).rstrip("\n")),
        (
            "    sendCommand(SPECTRA133_REGISTER_DRF, SPECTRA133_REGISTER_DRF_V, sizeof(SPECTRA133_REGISTER_DRF_V), eChipIdBoth);\n    waitForBusy();",
            hook(3) + "    sendCommand(SPECTRA133_REGISTER_DRF, SPECTRA133_REGISTER_DRF_V, sizeof(SPECTRA133_REGISTER_DRF_V), eChipIdBoth);\n    waitForBusy();\n" + hook(4).rstrip("\n"),
        ),
        ("        setPanelState(false);\n    displayEnd();", "        setPanelState(false);\n" + hook(5) + "    displayEnd();"),
    )
    for before, after in replacements:
        count = body.count(before)
        if count != 1:
            raise RuntimeError(f"Expected one partial timing anchor, found {count}: {before!r}")
        body = body.replace(before, after, 1)
    return (text[:start] + DECLARATION + body + text[end:]).encode("utf-8")


def prepare_timing_library(source: Path | None = None, destination: Path | None = None) -> Path:
    source = (source or Path(os.environ.get(
        "INKPLATE_LIBRARY_DIR", str(Path.home() / "Arduino/libraries/InkplateLibrary")
    ))).expanduser().resolve()
    destination = (destination or DEFAULT_DESTINATION).expanduser().resolve()
    if source == destination or source in destination.parents or destination in source.parents:
        raise RuntimeError("Timing library destination must not overlap the installed source library")
    original = (source / DRIVER).read_bytes()
    patched = instrument_driver(original)  # Reject unknown sources before changing build output.
    if not (source / "library.properties").is_file():
        raise RuntimeError(f"Missing library.properties in {source}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".inkplate-timing-", dir=destination.parent) as temp:
        staging = Path(temp) / "InkplateLibrary"
        shutil.copytree(source / "src", staging / "src")
        shutil.copy2(source / "library.properties", staging / "library.properties")
        (staging / DRIVER).write_bytes(patched)
        (staging / "src/AvianPartialTiming.h").write_text(STAMP, encoding="utf-8")
        if destination.exists():
            shutil.rmtree(destination)
        staging.rename(destination)
    return destination


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="Installed library (or INKPLATE_LIBRARY_DIR)")
    parser.add_argument("--destination", type=Path, help="Private build library directory")
    args = parser.parse_args()
    print(prepare_timing_library(args.source, args.destination))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, RuntimeError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        raise SystemExit(1)
